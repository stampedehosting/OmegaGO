"""Shared dataclasses and contracts that flow through the asyncio queues.

The orchestrator wires components together through three queues:

    chat_in    : ChatMessage   ->  llm
    reply_out  : LLMReply      ->  tts
    audio_out  : AudioChunk    ->  avatar
    frame_out  : VideoFrame    ->  output

Each component implements an `async def run(in_q, out_q, ctx)` coroutine.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Optional
import time
import uuid


class Platform(str, Enum):
    YOUTUBE = "youtube"
    TWITCH = "twitch"
    TIKTOK = "tiktok"
    LINKEDIN = "linkedin"
    LOCAL = "local"  # for dev/CLI


@dataclass
class ChatMessage:
    """A single inbound chat message from any platform."""
    id: str
    platform: Platform
    user: str
    text: str
    is_member: bool = False
    is_mod: bool = False
    superchat_amount: float = 0.0   # YouTube/TikTok gifts normalized to USD
    received_at: float = field(default_factory=time.time)

    @staticmethod
    def new(platform: Platform, user: str, text: str, **kw) -> "ChatMessage":
        return ChatMessage(id=str(uuid.uuid4()), platform=platform, user=user, text=text, **kw)


@dataclass
class LLMReply:
    """A response generated by the LLM, ready to be spoken."""
    id: str
    in_reply_to: Optional[str]   # ChatMessage.id, or None for idle filler
    text: str
    persona_emotion: str = "neutral"   # neutral | happy | excited | thoughtful | concerned
    created_at: float = field(default_factory=time.time)


@dataclass
class AudioChunk:
    """A streaming PCM chunk from the TTS engine."""
    reply_id: str
    pcm: bytes               # 16-bit little-endian mono
    sample_rate: int = 24000
    is_final: bool = False   # last chunk for this reply


@dataclass
class VideoFrame:
    """A single composited output frame (avatar + overlay)."""
    reply_id: Optional[str]
    bgr: "any"               # numpy.ndarray HxWx3 uint8 — kept as 'any' to avoid hard numpy import here
    pts_ms: int              # presentation timestamp in milliseconds


@dataclass
class StreamContext:
    """Shared mutable runtime context passed to all components."""
    persona_name: str
    viewer_count: int = 0
    recent_chat: list[ChatMessage] = field(default_factory=list)
    last_reply_at: float = 0.0
    config: dict = field(default_factory=dict)
